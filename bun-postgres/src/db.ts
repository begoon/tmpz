import { SQL } from "bun";
export const db = new SQL(
  process.env.DATABASE_URI || process.env.DATABASE_URL || "",
  {
    max: 3,
    idleTimeout: 20,
    connectionTimeout: 10,
    prepare: false,
  },
);
export const types = [
  "text",
  "varchar(255)",
  "integer",
  "bigint",
  "numeric",
  "boolean",
  "date",
  "timestamp",
  "timestamptz",
  "uuid",
  "jsonb",
  "bytea",
] as const;

export const quote = (name: string) => '"' + name.replaceAll('"', '""') + '"';

export function identifier(value: string) {
  if (!value.trim() || value.includes("\0") || Buffer.byteLength(value) > 63)
    throw new Error("Names must contain 1–63 bytes and no null characters.");
  return quote(value);
}

export const relation = (name: string) => `"public".${identifier(name)}`;

export async function tables() {
  return (await db`SELECT c.relname AS name FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind IN ('r','p') ORDER BY c.relname`) as {
    name: string;
  }[];
}

export type Column = {
  name: string;
  type: string;
  nullable: boolean;
  default_value: string | null;
  identity: string;
  generated: string;
  primary_key: boolean;
};

export async function columns(table: string): Promise<Column[]> {
  const rows =
    await db`SELECT a.attname AS name, format_type(a.atttypid,a.atttypmod) AS type,
  NOT a.attnotnull AS nullable, pg_get_expr(d.adbin,d.adrelid) AS default_value,
  a.attidentity AS identity, a.attgenerated AS generated,
  EXISTS(SELECT 1 FROM pg_index i WHERE i.indrelid=c.oid AND i.indisprimary AND a.attnum=ANY(i.indkey)) AS primary_key
  FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
  LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
  WHERE n.nspname='public' AND c.relname=${table} AND c.relkind IN ('r','p') AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum`;
  if (!rows.length) throw new Error("Table not found, or it has no columns.");
  return rows as Column[];
}

export async function createTable(form: FormData) {
  const names = form.getAll("column").map(String),
    kinds = form.getAll("type").map(String);
  if (
    !names.length ||
    names.length > 50 ||
    new Set(names).size !== names.length
  )
    throw new Error("Provide 1–50 uniquely named columns.");
  const definitions = names.map((name, i) => {
    const type = kinds[i];
    if (!(types as readonly string[]).includes(type))
      throw new Error("Unsupported column type.");
    const key = form.get(`primary_${i}`) === "on";
    const auto = form.get(`auto_${i}`) === "on";
    if (auto && !["integer", "bigint"].includes(type))
      throw new Error("Auto increment requires integer or bigint.");
    return `${identifier(name)} ${type}${auto ? " GENERATED BY DEFAULT AS IDENTITY" : ""}${key ? " NOT NULL" : form.get(`required_${i}`) === "on" ? " NOT NULL" : ""}`;
  });
  const primary = names.filter((_, i) => form.get(`primary_${i}`) === "on");
  if (primary.length)
    definitions.push(`PRIMARY KEY (${primary.map(quote).join(",")})`);
  await db.unsafe(
    `CREATE TABLE ${relation(String(form.get("table") || ""))} (${definitions.join(",")})`,
  );
}

export async function insertRow(table: string, form: FormData) {
  const cols = await columns(table),
    names: string[] = [],
    values: (string | null)[] = [];
  cols.forEach((col, i) => {
    if (col.generated || col.identity === "a") return;
    const mode = form.get(`mode_${i}`) || "default";
    if (mode === "default") return;
    if (mode !== "value" && mode !== "null")
      throw new Error("Invalid value mode.");
    names.push(quote(col.name));
    values.push(mode === "null" ? null : String(form.get(`value_${i}`) ?? ""));
  });
  await db.unsafe(
    names.length
      ? `INSERT INTO ${relation(table)} (${names.join(",")}) VALUES (${values.map((_, i) => `$${i + 1}`).join(",")})`
      : `INSERT INTO ${relation(table)} DEFAULT VALUES`,
    values,
  );
}

export async function deleteRow(table: string, form: FormData) {
  const rows = await db.unsafe(
    `DELETE FROM ${relation(table)} WHERE ctid=$1::tid AND xmin::text=$2 AND tableoid=$3::oid RETURNING 1`,
    [
      String(form.get("tid")),
      String(form.get("version")),
      String(form.get("oid")),
    ],
  );
  if (!rows.length)
    throw new Error(
      "The row changed or was deleted. Refresh the table before trying again.",
    );
}
